def test_a_radar_frame_is_a_png_the_browser_can_cache(
    client: TestClient, radar_bundle: BundleLayout
) -> None:
    first = client.get(f"{RADAR_URL}/3.png")
    assert first.status_code == 200
    assert first.headers["content-type"] == "image/png"
    assert first.content.startswith(PNG_MAGIC)
    assert first.headers["cache-control"] == "public, max-age=3600"

    etag = first.headers["etag"]
    assert etag.startswith('W/"')  # weak: make bundle rewrites the cube, so never immutable
    again = client.get(f"{RADAR_URL}/3.png")
    assert again.headers["etag"] == etag
    assert again.content == first.content  # rendering is deterministic (rule 8)

    cached = client.get(f"{RADAR_URL}/3.png", headers={"If-None-Match": etag})
    assert cached.status_code == 304
    assert cached.content == b""
    assert cached.headers["etag"] == etag


