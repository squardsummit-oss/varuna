def test_the_clock_state_reaches_the_console_over_the_websocket(
    client: TestClient, bus: Bus
) -> None:
    with client.websocket_connect("/v1/live") as ws:
        assert ws.receive_json()["topic"] == "hello"
        # The relay task subscribes after the handshake; publishing before it does would be a
        # race the console never runs into (it subscribes once and stays).
        deadline = time.monotonic() + 2
        while bus.subscriber_count == 0 and time.monotonic() < deadline:
            time.sleep(0.01)

        target = (T0 + timedelta(minutes=45)).isoformat()
        client.post("/v1/replay/seek", json={"sim_time": target})

        # The socket also carries heartbeats (every 0.2 s in tests); skip them.
        for _ in range(10):
            event = ws.receive_json()
            if event["topic"] == "replay.clock":
                break
        assert event["topic"] == "replay.clock"
        assert event["payload"]["sim_time"] == target
        assert event["payload"]["bundle_id"] == BUNDLE_ID


